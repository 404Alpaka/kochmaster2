import 'auth_store.dart';

class TransientAuthStore implements AuthStore {
  final _values = <String, String>{};
  @override
  Future<String?> read(String key) async => _values[key];
  @override
  Future<void> write(String key, String? value) async {
    if (value == null) {
      _values.remove(key);
    } else {
      _values[key] = value;
    }
  }
}

AuthStore createStore() => TransientAuthStore();
